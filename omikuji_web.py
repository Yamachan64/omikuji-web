import streamlit as st
import random

# おみくじの結果のリスト（例）
omikuji_results = [
    "大吉✨: 今日は最高の運気！何か挑戦する日ですよ。",
    "中吉🌟: とても良い日です。計画通りに進めると良さそうです。",
    "小吉😊: 特に大きな変化はないかもしれませんが、焦らず進みましょう。",
    "吉🍀: 幸運が訪れそうです！特に人間関係に良いことがありそうです。",
    "凶⚠️: 少し注意が必要です。今日は休息をとり、心身を休めることをおすすめします。"
]

def draw_omikuji():
    """ランダムでおみくじの結果を選んで返す関数"""
    # リストから要素をランダムに選択する
    result = random.choice(omikuji_results)
    return result

# --- Streamlit アプリのメイン部分 ---

# 1. アプリケーションのタイトルを設定します (Streamlitの機能です)
st.title("🎋 おみくじアプリ")
st.write("ボタンを押して今日の運勢を占いましょう😊")

# 2. ボタンを作成し、押されたときの処理を定義します
# 「おみくじを引く」ボタンを表示します。
if st.button('✨ おみくじを引く ✨'):
    # ボタンがクリックされると実行される処理です
    # おみくじを引く関数を呼び出して結果を取得する
    result = draw_omikuji()

    # 3. 結果を見やすいように画面に表示します (成功メッセージなどと共に)
    st.balloons() # アニメーションで楽しい演出をします
    st.subheader("🎉 あなたのおみくじの結果は… 🎉")
    # 結果のテキストを大きな文字で見やすく表示します
    st.markdown(f"### {result}")

    # 初心者向けの説明や補足情報を加えることもできます
    st.info("今日の運勢を楽しんでくださいね！😊")

# アプリが実行されると、初期状態ではボタンだけが表示され、クリックを待機します。
